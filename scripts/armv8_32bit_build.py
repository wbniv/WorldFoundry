#!/usr/bin/env python3
"""Build, package and measure an ARMv8 32-bit (armeabi-v7a) engine library beside the shipped ARMv7 one.

    python3 scripts/armv8_32bit_build.py probe                     codegen of the Forth words and a Jolt file, both ways
    python3 scripts/armv8_32bit_build.py build --variant v7|v8     libwf_dream.so for armeabi-v7a in the linux-test container
    python3 scripts/armv8_32bit_build.py histogram                 instruction counts and libm imports of both libraries
    python3 scripts/armv8_32bit_build.py package --base APK        the Aquarium APK with each library swapped in, signed
    python3 scripts/armv8_32bit_build.py recipe --variant v7|v8 --device D   a coordinator profile request (Lionfish)
    python3 scripts/armv8_32bit_build.py summarize EVIDENCE...     FPS of each run over the same steady window
    python3 scripts/armv8_32bit_build.py clean                     delete this script's build output

Plan: docs/plans/2026-11-26-armv8-32bit-build.md. A measurement harness: it never changes the shipped build.
`v7` is the NDK default for armeabi-v7a (-march=armv7-a -mthumb, VFPv3-D16 + NEON); `v8` adds
-march=armv8-a -mfpu=neon-fp-armv8 -mfloat-abi=softfp. Both are built the same way from the same tree,
reproducing AGP's CMake call for the screensaver Release (android/screensaver/build.gradle.kts), so
the two libraries differ only in those flags.

The linux-test image has no armv7-linux-androideabi Rust standard library, so the build puts a `cargo`
shim first on PATH that copies in the Rust attribute validator archive AGP built on the host for the
shipped APK (scripts/build-runtime-property-core.py's output). C flags never reach Rust code, so both
variants and the shipped APK link the same archive; its SHA-256 is recorded in the build receipt.
"""
