def main(argv):
    if len(argv) > 1 and argv[1] in ('-h', '--help'):
        print(__doc__)
        return 0
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    dump, out = Path(argv[1]), Path(argv[2])
    out.mkdir(parents=True, exist_ok=True)
    for case, base, title, mid, extreme, colour in CASES:
        j = json.loads((dump / f'{case}.json').read_text())
        faces = triples(j['faces'])
        poses = [triples(j['rest']), triples(j['steps'][mid]), triples(j['steps'][extreme])]
        rest_n = [normal(poses[0], f) for f in faces]
        allv = [v for p in poses for v in p]
        lo = [min(v[i] for v in allv) for i in range(3)]
        hi = [max(v[i] for v in allv) for i in range(3)]
        centre = tuple((min(v[i] for v in poses[2]) + max(v[i] for v in poses[2])) / 2 for i in range(3))
        radius = max(math.sqrt(dot(sub(v, centre), sub(v, centre))) for v in poses[2])
        d = choose_camera(poses[2], faces, rest_n, centre, radius)
        eye = tuple(centre[i] + d[i] * 3 * radius for i in range(3))
        data = {'vertices': len(poses[0]), 'faces': [i for f in faces for i in f], 'lo': lo, 'hi': hi,
                'poses': pack(poses, lo, hi), 'centre': centre, 'radius': radius, 'dir': d, 'colour': colour}
        html = PAGE % {'title': title, 'mesh': j['mesh'], 'data': json.dumps(data, separators=(',', ':'))}
        (out / f'{base}.html').write_text(html)
        c, w, e = stats(poses[2], faces, rest_n, eye)
        print(f'{base:6s} {len(faces):5d} faces  extreme pose: {c} culled wrongly, {w} drawn wrongly, '
              f'max error {e:.3f}; {len(html) // 1024} KB')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
