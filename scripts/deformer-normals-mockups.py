def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def normal(p, f):
    n = cross(sub(p[f[1]], p[f[0]]), sub(p[f[2]], p[f[0]]))
    length = math.sqrt(dot(n, n))
    return None if length <= 1e-12 else (n[0] / length, n[1] / length, n[2] / length)


def triples(flat):
    return [tuple(flat[i:i + 3]) for i in range(0, len(flat), 3)]


def camera_basis(d):
    up = (0.0, 0.0, 1.0) if abs(d[2]) < 0.95 else (0.0, 1.0, 0.0)
    right = cross(up, d)
    rl = math.sqrt(dot(right, right))
    right = tuple(c / rl for c in right)
    return right, cross(d, right)


def choose_camera(pose, faces, rest_n, centre, radius):
    """The view direction (unit, eye = centre + d * 3 radius) with the most screen area that changes."""
    best, best_score = None, -1.0
    count = 256
    for k in range(count):
        z = 1 - 2 * (k + 0.5) / count
        r = math.sqrt(max(0.0, 1 - z * z))
        phi = k * math.pi * (3 - math.sqrt(5))
        d = (r * math.cos(phi), r * math.sin(phi), z)
        eye = tuple(centre[i] + d[i] * 3 * radius for i in range(3))
        right, up = camera_basis(d)
        score = 0.0
        for fi, f in enumerate(faces):
            nr, np_ = rest_n[fi], normal(pose, f)
            if nr is None or np_ is None:
                continue
            c = tuple(sum(pose[v][i] for v in f) / 3 for i in range(3))
            to = sub(c, eye)
            if (dot(nr, to) > 0) == (dot(np_, to) > 0):
                continue
            pts = []
            for v in f:
                q = sub(pose[v], eye)
                depth = -dot(q, d)
                if depth <= 1e-6:
                    break
                pts.append((dot(q, right) / depth, dot(q, up) / depth))
            if len(pts) == 3:
                score += abs((pts[1][0] - pts[0][0]) * (pts[2][1] - pts[0][1])
                             - (pts[2][0] - pts[0][0]) * (pts[1][1] - pts[0][1])) / 2
        if score > best_score:
            best, best_score = d, score
    return best


def pack(poses, lo, hi):
    out = bytearray()
    for p in poses:
        for v in p:
            for i in range(3):
                span = hi[i] - lo[i] or 1.0
                out += struct.pack('<H', round((v[i] - lo[i]) / span * 65535))
    return base64.b64encode(bytes(out)).decode()


def stats(pose, faces, rest_n, eye):
    culled = drawn = 0
    err = 0.0
    for fi, f in enumerate(faces):
        nr, np_ = rest_n[fi], normal(pose, f)
        if nr is None or np_ is None:
            continue
        err = max(err, max(abs(nr[i] - np_[i]) for i in range(3)))
        c = tuple(sum(pose[v][i] for v in f) / 3 for i in range(3))
        stale, true = dot(nr, sub(c, eye)) > 0, dot(np_, sub(c, eye)) > 0
        culled += stale and not true
        drawn += true and not stale
    return culled, drawn, err


