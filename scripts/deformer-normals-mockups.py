#!/usr/bin/env python3
"""deformer-normals-mockups.py: before/after mockups for the deformer face-normal fix.

Reads the pose dumps written by `deformer_golden_test <repo> <dump-dir> --dump` (real aquarium meshes,
posed by the engine's own deformers) and writes one self-contained 1440x900 HTML page per species
deformer into the plan's bundle directory. Each page re-renders the rest, mid and extreme pose twice in
a canvas: once culled and lit with the rest-pose normals the engine stored before the fix, once with
normals recomputed from the posed triangles (the fix). Culling is the engine's test
(backface_cull.hp: the face is dropped when dot(N, centre - eye) > 0); lighting is one directional
light on flat faces. The camera is chosen from the mesh data: of 256 view directions, the one where the
faces whose cull decision changes cover the largest screen area at the extreme pose.

  scripts/deformer-normals-mockups.py DUMP_DIR OUT_DIR

PNGs are taken separately with headless Chrome (see docs/plans/2026-11-01-deformer-face-normals.md).
"""
