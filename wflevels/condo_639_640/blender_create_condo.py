        # bottom_i + park_i*p + H*c == bottom_(i-1) + park_(i-1)*p.
        # Scale affects rendering only; Jolt collision and the bar keep their motion.
        scales = "".join(f"dup 1 swap - 3042 {idx0 + k} write-actor-mailbox "
                         for k in range(SLAT_N))
