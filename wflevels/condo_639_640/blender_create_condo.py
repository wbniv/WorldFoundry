def sanitize(name):
    """Blender name → asset filename slug: lowercase, runs of non-alnum → '_'.

    The engine's asset string map holds 31 bytes per name (assets.cc
    ReadAssetMap asserts `BytesLeft() < 32`), so `<slug>.iff` must stay ≤ 30
    chars: long names are cut to 21 chars + a 4-hex hash of the full name.
    """
    import zlib
    slug = re.sub(r'[^a-z0-9]+', '_', name.lower()).strip('_')
    if len(slug) > 26:
        slug = f"{slug[:21].rstrip('_')}_{zlib.crc32(name.encode()) & 0xffff:04x}"
    return slug


def make_flat_material(name, rgb):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = next((n for n in mat.node_tree.nodes if n.type == 'BSDF_PRINCIPLED'), None)
    if bsdf:
        bsdf.inputs['Base Color'].default_value = (*rgb, 1.0)
    mat.diffuse_color = (*rgb, 1.0)
    return mat


def set_sheet_opacity(mat, opacity):
    """Explicit engine opacity, mirrored in Blender; prelit sheets read equally from both sides."""
    assert 0.0 <= opacity <= 1.0
    mat['wf_opacity'] = opacity
    mat['wf_double_sided'] = True
    mat['wf_prelit'] = True
    mat.diffuse_color = (*mat.diffuse_color[:3], opacity)
    bsdf = next(n for n in mat.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    bsdf.inputs['Alpha'].default_value = opacity
    bsdf.inputs['Base Color'].default_value = (*bsdf.inputs['Base Color'].default_value[:3], opacity)
    if hasattr(mat, 'surface_render_method'):
        mat.surface_render_method = 'DITHERED'
    return mat


def add_optical_sheet(bm, x0, x1, y, z0, z1, material_index):
    """One quad, rendered from either side; collision boxes remain separate invisible faces."""
    face = bm.faces.new([bm.verts.new(co) for co in
                         ((x0, y, z0), (x1, y, z0), (x1, y, z1), (x0, y, z1))])
    face.material_index = material_index


def bake_transform(obj):
    """Fold rotation+scale (and any parent transform) into the mesh verts, leaving
    only a translation on the object. The Jolt trimesh body is built from raw
    local verts and ignores actor scale/rotation (troubleshooting § "Per-actor
    scale"), and the render path shears a rotated non-uniform scale."""
    mw = obj.matrix_world.copy()
    obj.parent = None
    if obj.data.users > 1:
        obj.data = obj.data.copy()
    rs = mw.to_3x3()
    for v in obj.data.vertices:
        v.co = rs @ v.co
    obj.matrix_world = Matrix.Translation(mw.to_translation())
    obj.data.update()


# The engine computes each face normal at load as (v2−v0)×(v1−v0) and asserts its
# length > Scalar(0,4) ≈ 6.1e-5 in 1.15.16 fixed point (math/vector3.hpi:243,
# "Probably have a polygon which is too small") — i.e. any triangle with area
# < ~3e-5 m² aborts the level. Bevelled-curve corners produce exactly those.
MIN_FACE_AREA = 8e-5
_dropped = {'faces': 0}


def clean_mesh(mesh, recalc=True):
    import bmesh
    bm = bmesh.new()
    bm.from_mesh(mesh)
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)
    bmesh.ops.triangulate(bm, faces=bm.faces)
    tiny = [f for f in bm.faces if f.calc_area() < MIN_FACE_AREA]
    if tiny:
        _dropped['faces'] += len(tiny)
        bmesh.ops.delete(bm, geom=tiny, context='FACES_ONLY')
        bmesh.ops.delete(bm, geom=[v for v in bm.verts if not v.link_faces], context='VERTS')
    if recalc:
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(mesh)
    bm.free()
    mesh.update()


def curve_to_mesh(obj):
    """Bevelled POLY curve → tube mesh object of the same name (materials kept)."""
    dg = bpy.context.evaluated_depsgraph_get()
    ev = obj.evaluated_get(dg)
    me = bpy.data.meshes.new_from_object(ev, preserve_all_data_layers=True, depsgraph=dg)
    if not me.materials:
        for m in obj.data.materials:
            me.materials.append(m)
    me.name = obj.name
    cols = list(obj.users_collection)
    name, mw = obj.name, obj.matrix_world.copy()
    bpy.data.objects.remove(obj, do_unlink=True)
    new = bpy.data.objects.new(name, me)
    new.matrix_world = mw
    for c in cols:
        c.objects.link(new)
    return new


def as_statplat(obj):
    attach_schema(obj, 'statplat')
    obj['wf_Mobility']           = 'Anchored'
    obj['wf_Model Type']         = 'Mesh'
    obj['wf_Visibility Mailbox'] = 1
    # Actor NAME stays the Blender name; the mesh file gets a dot/hyphen-free slug
    # so the asset tools never see `foo.001.iff`.
    obj['wf_original_mesh_name'] = sanitize(obj.name) + '.iff'


def collection_hidden(obj):
    return any(c.hide_viewport or c.hide_render for c in obj.users_collection)


