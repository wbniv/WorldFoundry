#!/usr/bin/env python3
"""Generate the Minute Machine director script (zForth).

The director poses every moving piece each frame from three numbers, WALL_HOUR, WALL_MINUTE and
WALL_SECOND, and from nothing else: no state survives a frame except the scratch cells.

    director_script(indices) -> str     indices: actor name -> runtime index

Piecewise motions are emitted from channels.py (value = base + sum of delta * ease(seg)), which
tests/test_minute_machine_channels.py proves equal to timeline.py. The dominoes, the flap cards,
the bell and the camera are loops and formulas that follow timeline.py's functions one for one.
Global user mailbox cells 600..699 are the scratch variables.
"""
from __future__ import annotations

import argparse
import json
import sys
from typing import Dict, List

import channels as ch
import timeline as tl

PX = tl.PX


def n(x: float) -> str:
    s = f"{x:.8f}".rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def w(name: str) -> str:
    return name.replace("_", "-")


# timeline pieces that are posed through another actor: the camera is a CamShot and its look-at target
ACTOR_OF = {"camera_proxy": "cs_wide", "camera_look": "LookAt"}

CELLS = ["t", "hr", "mi", "phr", "pmi", "k", "n", "cur", "prv", "st", "tau", "acc", "j", "i", "q", "pos",
         "f", "r", "ci", "dg", "az", "p", "dist", "tx", "see", "fill", "sn", "cs"]


def check_names() -> None:
    """A scratch cell and a word must never share a name: the later definition shadows the earlier."""
    words = {"x", "y", "z", "a", "b", "c", "sz", "u", "lin", "sq", "sm", "frac", "mod", "sin", "c01", "dig", "size",
             "drum", "card-deg", "cbase", "cards", "dominoes", "tick"}
    clash = words & set(CELLS)
    assert not clash, f"scratch cells shadow words: {sorted(clash)}"


def library() -> str:
    check_names()
    out: List[str] = ["\\ Minute Machine director (generated by wflevels/minute_machine/forth.py; do not edit)",
                      ": mm@ read-mailbox ; : mm! write-mailbox ;"]
    for i, name in enumerate(CELLS):
        out.append(f": mm-{name} {600 + i} ;")
    out += [
        ": mm-c01 0 max 1 min ;",
        ": mm-u ( a b -- u ) over - >r mm-t mm@ swap - r> / mm-c01 ;",
        ": mm-lin mm-u ;",
        ": mm-sq mm-u dup * ;",
        ": mm-sm mm-u dup dup * swap 2 * 3 swap - * ;",
        ": mm-frac dup floor - ;",                                    # the engine's floor (docs/forth-math-words.md)
        ": mm-mod ( a b -- r ) over over / floor * - ;",            # floored: takes the divisor's sign, unlike fmod
        ": mm-sin sin-rev ;",
        ": mm-x ( v actor -- ) INDEXOF_X_POS swap write-actor-mailbox ;",
        ": mm-y ( v actor -- ) INDEXOF_Y_POS swap write-actor-mailbox ;",
        ": mm-z ( v actor -- ) INDEXOF_Z_POS swap write-actor-mailbox ;",
        ": mm-a ( v actor -- ) INDEXOF_ROTATION_A swap write-actor-mailbox ;",
        ": mm-b ( v actor -- ) INDEXOF_ROTATION_B swap write-actor-mailbox ;",
        ": mm-c ( v actor -- ) INDEXOF_ROTATION_C swap write-actor-mailbox ;",
        ": mm-sz ( v actor -- ) INDEXOF_Z_SCALE swap write-actor-mailbox ;",
    ]
    # channels
    for name, c in ch.CHANNELS.items():
        body = n(c.base)
        for d, (a, b, kind) in zip(c.deltas, c.steps):
            body += f" {n(d)} {n(a)} {n(b)} mm-{kind} * +"
        out.append(f": mm-c-{w(name)} {body} ;")
    return "\n".join(out) + "\n"


def pieces(ix: Dict[str, int]) -> str:
    A = lambda name: str(ix[name])
    out: List[str] = []
    out.append(f": mm-ch ( name -- ) drop ;")      # placeholder keeps the dictionary layout stable
    def put(expr: str, setter: str, piece: str) -> None:
        out.append(f"  {expr} {A(piece)} {setter}")

    body: List[str] = []
    body.append("  INDEXOF_WALL_SECOND mm@ mm-t mm!  INDEXOF_WALL_HOUR mm@ mm-hr mm!  INDEXOF_WALL_MINUTE mm@ mm-mi mm!")
    body.append("  mm-mi mm@ 1 - mm-pmi mm!  mm-hr mm@ mm-phr mm!")
    body.append("  mm-pmi mm@ 0 < if 59 mm-pmi mm! mm-phr mm@ 1 - mm-phr mm! mm-phr mm@ 0 < if 23 mm-phr mm! then then")

    def b(expr: str, setter: str, piece: str) -> None:
        body.append(f"  {expr} {A(piece)} {setter}")

    b(f"mm-c-marble-x {n(PX)} *", "mm-x", "marble")
    b(f"{n(tl.TABLE)} mm-c-marble-y - {n(PX)} *", "mm-z", "marble")
    body.append("  mm-dominoes")
    body.append(f"  mm-c-seesaw {n(2 * tl.SEESAW_TILT_DEG)} * {n(tl.SEESAW_TILT_DEG)} - negate 360 / mm-see mm!")
    b("mm-see mm@", "mm-b", "seesaw")           # mm-see is the roll b itself, in revolutions
    right = tl.SEESAW_PIVOT[1]
    b(f"{n(tl.TABLE - right)} {n(tl.SEESAW_HALF)} mm-see mm@ negate mm-sin * + {n(PX)} *", "mm-z", "rod")   # the tilt angle is -b
    b(f"808 22 mm-c-gate-open * - {n(PX)} *", "mm-x", "hopper_gate")
    b(f"{n(tl.zm(tl.GATE_Y - 16.0))} {n(22.0 * PX)} mm-c-gate-lift * +", "mm-z", "rail_gate")
    body.append("  mm-c-bucket-fill mm-fill mm!")
    b("mm-c-hopper-fill .0001 max", "mm-sz", "hopper_sand")
    b(f"{n(tl.TABLE - tl.BUCKET_TOP)} {n(tl.BUCKET_SINK)} mm-fill mm@ * - {n(PX)} *", "mm-z", "bucket")
    b("mm-c-bucket-tip 105 * 360 / negate", "mm-b", "bucket")
    b(f"{n(tl.TABLE - tl.BUCKET_TOP - tl.BUCKET_H)} {n(tl.BUCKET_SINK)} mm-fill mm@ * - {n(PX)} *", "mm-z", "bucket_sand")
    b("mm-fill mm@ .0001 max", "mm-sz", "bucket_sand")
    b("mm-c-trough-fill .0001 max", "mm-sz", "trough_sand")
    b("mm-c-stream .0001 max", "mm-sz", "stream")
    b("mm-c-pour .0001 max", "mm-sz", "pour")
    b(f"{n(tl.TABLE - tl.BUCKET_TOP - 14.0)} {n(tl.BUCKET_SINK)} mm-fill mm@ * - {n(PX)} *", "mm-z", "pour")
    b(f"{n(tl.BUCKET_TOP - 18.0 - tl.PULLEY_Y)} {n(tl.BUCKET_SINK)} mm-fill mm@ * + {n(PX)} *", "mm-sz", "string_l")
    b(f"{n(tl.SPRING_TOP_REST - tl.PULLEY_Y)} {n(tl.BUCKET_SINK)} mm-fill mm@ * - {n(PX)} *", "mm-sz", "string_r")
    b(f"{n(tl.TABLE - tl.SPRING_TOP_REST)} {n(tl.BUCKET_SINK)} mm-fill mm@ * + {n(PX)} *", "mm-z", "spring")
    b(f"{n(tl.SPRING_REST)} {n(tl.BUCKET_SINK)} mm-fill mm@ * + mm-c-pin-px - {n(tl.SPRING_REST)} /", "mm-sz", "spring")
    b(f"{n(tl.TABLE - tl.PIN_TOP_REST)} mm-c-pin-px + {n(PX)} *", "mm-z", "pin")
    body.append("  mm-t mm@ 55 >= if mm-t mm@ mm-frac dup .25 < if 2 * mm-sin else drop 0 then else 0 then "
                f"22 * 360 / negate {A('pawl')} mm-b")
    b(f"30 57 mm-lin {tl.MARBLE_LIFT_TURNS} * mm-frac", "mm-c", "marble_lift_screw")
    b(f"7 20 mm-lin {tl.SAND_LIFT_TURNS} * mm-frac", "mm-c", "sand_lift_screw")
    # bell and hammer: on the hour only
    body.append("  mm-mi mm@ 0 = if")
    body.append("    mm-t mm@ .5 > mm-t mm@ 7.5 < & if")
    body.append("      mm-t mm@ .5 - mm-q mm!")
    body.append("      1 mm-q mm@ 7 / - dup * 16 * 360 / mm-q mm@ 1.3 * mm-sin *")
    body.append(f"    else 0 then {A('bell')} mm-b")
    body.append(f"    mm-c-hammer-deg 360 / {A('hammer')} mm-b")
    body.append(f"  else 0 {A('bell')} mm-b {n(24 / 360)} {A('hammer')} mm-b then")
    body.append("  mm-cards")
    # camera: drift from the minute of the ten-minute period, push-in from the channel
    body.append("  mm-mi mm@ 10 mm-mod 60 * mm-t mm@ + 600 / mm-sin "
                f"{n(tl.DRIFT_DEG / 360)} * mm-az mm!")
    body.append("  mm-az mm@ sincos-rev mm-cs mm! mm-sn mm!")        # one call for both: the camera's sine and cosine
    body.append("  mm-c-push mm-p mm!")
    body.append(f"  {n(tl.CAMERA_R_PX)} 1 {n(tl.PUSH_IN)} mm-p mm@ * + / mm-dist mm!")
    body.append(f"  {n(tl.SCENE_CENTRE[0])} {n((tl.LATCH_POINT[0] - tl.SCENE_CENTRE[0]) * tl.PUSH_IN * 4)} mm-p mm@ * + mm-tx mm!")
    b(f"mm-tx mm@ mm-dist mm@ mm-sn mm@ * + {n(PX)} *", "mm-x", "cs_wide")
    b(f"mm-dist mm@ mm-cs mm@ * negate {n(PX)} *", "mm-y", "cs_wide")
    b(f"{n(tl.zm(tl.SCENE_CENTRE[1]))}", "mm-z", "cs_wide")
    b(f"mm-tx mm@ {n(PX)} *", "mm-x", "LookAt")
    b(f"{n(tl.zm(tl.SCENE_CENTRE[1]))}", "mm-z", "LookAt")

    helpers = [
        # dominoes: f = 12 + i/3; r = 41 + i * step; the last one is quick and quadratic
        ": mm-dominoes",
        "  0 mm-i mm!",
        "  begin",
        f"    mm-i mm@ {n(tl.DOMINO_RATE)} / {n(tl.TL['dominoes'][0])} + mm-f mm!",
        f"    mm-i mm@ {n(tl.comb_step())} * {n(tl.TL['comb'][0])} + mm-r mm!",
        f"    mm-i mm@ {tl.DOMINO_COUNT - 1} = if",
        f"      mm-t mm@ mm-f mm@ - {n(tl.DOMINO_RATE)} * mm-c01 dup * {n(tl.LAST_DOMINO_DEG)}",
        "    else",
        f"      mm-t mm@ mm-f mm@ - 2 / mm-c01 {n(tl.DOMINO_LEAN_DEG)}",
        "    then >r",
        f"    mm-t mm@ mm-r mm@ - {n(tl.COMB_REARM_EASE)} / mm-c01 dup dup * swap 2 * 3 swap - * -",
        f"    r> * 360 / {ix['domino_00']} mm-i mm@ + mm-b",
        f"    mm-i mm@ 1 + dup mm-i mm! {tl.DOMINO_COUNT} =",
        "  until ;",
        # drums: digit k of (hour, minute)
        ": mm-dig ( hr mi k -- d )",
        "  dup 0 = if drop drop 10 / floor else",
        "  dup 1 = if drop drop 10 mm-mod else",
        "  dup 2 = if drop nip 10 / floor else",
        "  drop nip 10 mm-mod then then then ;",
        ": mm-size mm-k mm@ 0 = if 3 else mm-k mm@ 2 = if 6 else 10 then then ;",
        ": mm-drum",
        "  mm-size mm-n mm!",
        "  mm-hr mm@ mm-mi mm@ mm-k mm@ mm-dig mm-cur mm!",
        "  mm-phr mm@ mm-pmi mm@ mm-k mm@ mm-dig mm-prv mm!",
        "  mm-cur mm@ mm-prv mm@ - mm-n mm@ + mm-n mm@ mm-mod mm-st mm!",
        f"  mm-t mm@ 3 mm-k mm@ - {n(tl.CASCADE)} * - mm-tau mm!",
        "  0 mm-acc mm! 0 mm-j mm!",
        "  begin mm-j mm@ mm-st mm@ < if",
        f"    mm-tau mm@ mm-j mm@ {n(tl.FLIP_STEP)} * - {n(tl.FLIP)} / mm-c01 mm-acc mm@ + mm-acc mm!",
        "    mm-j mm@ 1 + mm-j mm! 0 else 1 then until",
        "  mm-prv mm@ mm-acc mm@ + mm-n mm@ mm-mod mm-pos mm! ;",
        ": mm-card-deg ( q -- deg )",
        "  dup 1 <= if dup * 180 * else",
        "    dup mm-n mm@ 1 - < if drop 180 else",
        "      mm-n mm@ 1 - - 2 * mm-c01 dup dup * swap 2 * 3 swap - * 1 swap - 180 *",
        "    then then ;",
        f": mm-card-y ( q -- y ) dup 1 <= if drop 0 else dup mm-n mm@ 1 - < if 1 - {n(tl.CARD_STACK)} * else "
        f"mm-n mm@ 1 - - 2 * mm-c01 dup dup * swap 2 * 3 swap - * 1 swap - mm-n mm@ 2 - {n(tl.CARD_STACK)} * * then then ;",
        ": mm-cbase mm-k mm@ 0 = if "
        f"{ix['card_0_0']} else mm-k mm@ 1 = if {ix['card_1_0']} else mm-k mm@ 2 = if {ix['card_2_0']} else {ix['card_3_0']} then then then ;",
        ": mm-cards",
        "  0 mm-k mm!",
        "  begin",
        "    mm-drum",
        "    0 mm-ci mm!",
        "    begin",
        "      mm-pos mm@ mm-ci mm@ - mm-n mm@ + mm-n mm@ mm-mod mm-q mm!",
        "      mm-q mm@ mm-card-deg 360 / mm-cbase mm-ci mm@ + mm-a",
        "      mm-q mm@ mm-card-y mm-cbase mm-ci mm@ + mm-y",
        "      mm-ci mm@ 1 + dup mm-ci mm! mm-n mm@ =",
        "    until",
        "    mm-k mm@ 1 + dup mm-k mm! 4 =",
        "  until ;",
    ]
    tick = [": mm-tick"] + body + [";"]
    return "\n".join(helpers + [""]) + "\n" + "\n".join(tick) + "\n"


def default_indices() -> Dict[str, int]:
    """Made-up actor indices for tests: dominoes and each drum's cards contiguous, as the level builder guarantees."""
    names = (["marble", "seesaw", "rod", "hopper_gate", "rail_gate", "hopper_sand", "bucket", "bucket_sand", "trough_sand",
              "stream", "pour", "string_l", "string_r", "spring", "pin", "pawl", "marble_lift_screw", "sand_lift_screw",
              "bell", "hammer", "cs_wide", "LookAt"]
             + [f"domino_{i:02d}" for i in range(tl.DOMINO_COUNT)]
             + [f"card_{k}_{c}" for k in range(4) for c in range(tl.DRUM_SIZES[k])])
    return {name: 100 + i for i, name in enumerate(names)}


def definitions(ix: Dict[str, int]) -> str:
    """The script without its per-frame body (the last line, mm-tick)."""
    return library() + pieces(ix)


def director_script(ix: Dict[str, int]) -> str:
    return library() + pieces(ix) + "\nmm-tick\n"


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--indices", metavar="actor-map.json", help="actor-map.json from the level build (indices: name -> index)")
    ap.add_argument("--out", metavar="FILE.fth", help="write the script here (default: stdout)")
    args = ap.parse_args(argv)
    ix = json.load(open(args.indices))["indices"] if args.indices else default_indices()
    text = director_script(ix)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
