def frame_words(ix: Dict[str, int]) -> List[str]:
    A = lambda name: str(ix[name])
    t, tide = get("t"), get("tide")
    L: List[str] = []
    # the river
    bar0 = ix["bar_00"]
    f0, f1 = tl.WAVE_F
    k0, k1 = tl.WAVE_K
    L += [": th-bars", "  0 th-i th!", "  begin",
          f"    1 {get('i')} {tl.N_BARS - 1} / - dup * .14 * .03 + {cell('kk')} th!",
          f"    {t} {n(f0)} * {get('i')} {n(k0)} * + sin-rev .6 * {t} {n(f1)} * {get('i')} {n(k1)} * - sin-rev .4 * +",
          f"    {get('kk')} * {tide} + {tl.N_BARS - 1} {get('i')} - .01 * + {bar0} {get('i')} + th-z",
          f"    {t} {n(f0)} * {get('i')} {n(k0)} * + .25 + sin-rev .004 * {bar0} {get('i')} + th-a",
          f"    {get('i')} 1 + dup th-i th! {tl.N_BARS} =", "  until ;"]
    # boats, ropes, raft, hyacinth, the gauge pointer
    L.append(": th-boats")
    for i, (name, bx, by, length, moored, ph) in enumerate(tl.BOATS):
        L.append(f"  {t} .2 * {n(0.137 * i)} + sin-rev .06 * {tide} + {cell('bz')} th! {get('bz')} {A(name)} th-z")
        L.append(f"  {t} .15 * {n(0.31 * i)} + sin-rev .008 * {A(name)} th-b")
        if moored:
            L.append(f"  {t} 90 / {n(ph)} + sin-rev .012 * {A(name)} th-c")
        else:
            L.append(f"  {t} {n(tl.FERRY_PERIOD)} / th-frac {n(tl.FERRY_SPAN)} * {n(tl.FERRY_SPAN / 2)} - {A(name)} th-x")
        if name in tl.ROPED:
            rope = A("rope_" + name[-1])
            L.append(f"  {n(by - tl.PIER_FRONT_Y)} {cell('dy')} th! {get('bz')} {n(tl.BOW_RISE - tl.CLEAT_Z)} + {cell('dz')} th!")
            L.append(f"  {get('dz')} {get('dy')} atan2-rev {rope} th-a")
            L.append(f"  {get('dy')} dup * {get('dz')} dup * + sqrt {rope} th-sy")
    L.append(f"  {t} .13 * sin-rev .03 * {tide} + {A('raft')} th-z  {t} .09 * .2 + sin-rev .006 * {A('raft')} th-a")
    for i, (x0, y0, ph) in enumerate(tl.HYACINTH):
        name = A(f"hyacinth_{i}")
        L.append(f"  {tide} {n(tl.Z0)} - {n(tl.HYACINTH_DRIFT)} * {n(x0)} + {name} th-x"
                 f"  {t} .17 * {n(ph)} + sin-rev .02 * {tide} + {name} th-z  {t} 1800 / {n(ph)} + th-frac {name} th-c")
    L.append(f"  {tide} {A('gauge_pointer')} th-z ;")
    # the sky: sun, moon, clouds, birds
    k_sun = (tl.SUN_Y - tl.CAMERA_REF[1])
    L += [": th-sky",
          f"  {get('son')} if {n(k_sun)} {get('we')} / {cell('kk')} th!",
          f"    {get('no')} {get('kk')} * {n(tl.CAMERA_REF[0])} + {A('sun')} th-x",
          f"    {get('up')} {get('kk')} * {n(tl.CAMERA_REF[2])} + -40 max {A('sun')} th-z",
          f"  else {n(tl.PARK[0])} {A('sun')} th-x {n(tl.PARK[2])} {A('sun')} th-z then",
          f"  {get('mon')} if 60 120 {get('mf')} * - {A('moon')} th-x {get('mf')} .5 * sin-rev 30 * 4 + {A('moon')} th-z",
          f"  else {n(tl.PARK[0])} {A('moon')} th-x {n(tl.PARK[2])} {A('moon')} th-z then"]
    for i, (z, period, ph, _half) in enumerate(tl.CLOUDS):
        per_day = 86400.0 / period                      # a whole number: the day wraps cleanly
        # the hour's share first, reduced to a fraction (exact: per_day / 24 is a whole or half number), then the second's
        L.append(f"  {get('hr')} {n(per_day / 24.0)} * th-frac {t} {n(per_day / 86400.0)} * + {n(ph)} + th-frac "
                 f"{n(tl.CLOUD_SPAN)} * {n(tl.CLOUD_SPAN / 2)} - {A(f'cloud_{i}')} th-x")
    for i, (period, ph, z, y) in enumerate(tl.BIRDS):
        name = A(f"bird_{i}")
        L.append(f"  {n(tl.BIRD_SPAN / 2)} {t} {n(period)} / {n(ph)} + th-frac {n(tl.BIRD_SPAN)} * - {name} th-x"
                 f"  {t} 36 / {n(ph)} + sin-rev 1.2 * {n(z)} + {name} th-z"
                 f"  {get('sec')} 2.5 * {n(ph)} + sin-rev abs .7 * .3 + {name} th-sz")      # 2.5 Hz: whole cycles per minute, so the second of the minute will do
    L.append(";")
    # lanterns and glints
    lan0, gl0 = ix["lantern_0"], ix["glint_0"]
    L += [": th-lights", "  0 th-i th!", "  begin",
          f"    {t} .3 * {get('i')} 8 / + sin-rev .012 * {lan0} {get('i')} + th-b",
          f"    {get('i')} 1 + dup th-i th! {len(tl.LANTERNS)} =", "  until"]
    for i, (x, y, ph, hz) in enumerate(tl.GLINTS):
        assert abs(hz * 60 - round(hz * 60)) < 1e-9                  # whole cycles per minute: the second of the minute will do
        L.append(f"  {get('sec')} {n(hz)} * {n(ph)} + sin-rev .05 max {gl0 + i} th-sx  {tide} .14 + {gl0 + i} th-z")
    L.append(";")
    # hands and camera
    lx, ly, lz = tl.LOOK_AT
    L += [": th-clock",
          f"  {get('hr')} 12 th-mod {get('mi')} 60 / + {get('sec')} 3600 / + 12 / {A('hand_h')} th-b",
          f"  {get('mi')} {get('sec')} 60 / + 60 / {A('hand_m')} th-b",
          f"  {get('sec')} 60 / {A('hand_s')} th-b",
          f"  th-opt-drift th@ 0 = if {t} {n(tl.DRIFT_PERIOD)} / sin-rev {n(tl.DRIFT_DEG / 360.0)} * else 0 then",
          f"  sincos-rev {cell('cs')} th! {cell('sn')} th!",
          # the panel takes a side of the screen: the harbour is drawn smaller and shifted into what the panel leaves
          "  th-slide",
          f"  {n(1.0 - pn.SCALE_AT_PANEL)} {get('pv')} * 1 swap - {cell('ps')} th!",
          f"  {n(tl.CAMERA_R)} {get('ps')} / {cell('pd')} th!",
          f"  {get('pl')} if -1 else 1 then {n(pn.PANEL_FRAC * pn.TAN_V * pn.ASPECT)} * {get('pv')} * {get('pd')} * {n(lx)} + {cell('lx')} th!",
          f"  {get('sn')} {get('pd')} * {get('lx')} + {cell('cx')} th!",
          f"  {n(ly)} {get('cs')} {get('pd')} * - {cell('cy')} th!  {n(tl.CAMERA_Z)} {cell('cz')} th!",
          f"  {get('cx')} {A('cs_wide')} th-x {get('cy')} {A('cs_wide')} th-y {get('cz')} {A('cs_wide')} th-z",
          f"  {get('lx')} {A('LookAt')} th-x {n(ly)} {A('LookAt')} th-y {n(lz)} {A('LookAt')} th-z ;"]
    # visibility
    V = tl.VIS
    L += [": th-show",
          f"  {get('son')} {V['sun']} th!  {get('mon')} {V['moon']} th!",
          f"  th-opt-life th@ 0 = {cell('kk')} th!",
          f"  {get('kk')} {get('alt')} 0 > & if 1 else 0 then {V['birds']} th!",
          f"  {get('kk')} if 1 else 0 then {V['boats']} th!",
          f"  th-opt-gauge th@ 0 = if 1 else 0 then {V['gauge']} th!",
          f"  th-opt-numerals th@ 0 = if 1 else 0 then {V['numerals_thai']} th!",
          f"  th-opt-numerals th@ 1 = if 1 else 0 then {V['numerals_roman']} th!",
          f"  {sc('rise')} 1 = if 1 else 0 then {V['arrow_up']} th!",
          f"  {sc('rise')} 1 = if 0 else 1 then {V['arrow_dn']} th! ;"]
    return L


def sc(name: str) -> str:
    return f"th-sc-{name} th@"


def panel_words(ix: Dict[str, int]) -> List[str]:
    """The river panel (panel.py), one formula for one: th-slide gives which side and how much of the panel is on screen,
    th-pframe the camera's axes from the camera and look-at cells th-clock has set, th-pplace puts a part's mesh origin at
    its (u, v) in panel coordinates at its layer's depth, scaled by depth / DEPTH and turned to face the camera, and
    th-panel poses every part (the drums from the scan's picks, th-sc-pick)."""
    A = lambda name: str(ix[name])
    g = get
    out = [": th-slide",
           f"  {g('t')} 600 / th-floor {cell('pk')} th!  {g('t')} {g('pk')} 600 * - {cell('px')} th!",
           f"  {g('pk')} 2 th-mod {cell('pw')} th!",
           f"  {g('px')} {n(pn.SLIDE_S)} < if 1 {g('pw')} - 2 {g('pw')} * 1 - {g('px')} * {n(pn.SLIDE_S)} / + else {g('pw')} then",
           "  th-c01 dup dup * swap 2 * 3 swap - * " + f"{cell('pe')} th!",
           f"  {g('pe')} .5 < if 0 else 1 then {cell('pl')} th!  1 {g('pe')} 2 * - abs {cell('pv')} th!",
           f"  {g('pl')} if {n(-pn.HALF_W - pn.W / 2)} {n(pn.W)} {g('pv')} * + else {n(pn.HALF_W + pn.W / 2)} {n(pn.W)} {g('pv')} * - then {cell('pcu')} th! ;",
           # the panel is pinned to the camera the engine really has, which eases towards cs_wide rather than jumping to it
           # (about 10 % of the way a frame): the Camera actor's position and its pitch (b) and heading (c), in revolutions.
           # Its forward is (sin c cos b, cos c cos b, sin b); with no roll, right is (cos c, -sin c, 0) and up is right x forward.
           f": th-cam@ {ix['Camera']} read-actor-mailbox ;",
           ": th-pframe",
           f"  INDEXOF_X_POS th-cam@ {cell('kx')} th!  INDEXOF_Y_POS th-cam@ {cell('ky')} th!  INDEXOF_Z_POS th-cam@ {cell('kz')} th!",
           f"  INDEXOF_ROTATION_C th-cam@ sincos-rev {cell('pcc')} th! {cell('pcs')} th!",
           f"  INDEXOF_ROTATION_B th-cam@ sincos-rev {cell('pbc')} th! {cell('pbs')} th!",
           f"  {g('pcs')} {g('pbc')} * {cell('fx')} th!  {g('pcc')} {g('pbc')} * {cell('fy')} th!  {g('pbs')} {cell('fz')} th!",
           f"  {g('pcc')} {cell('rx')} th!  0 {g('pcs')} - {cell('ry')} th!",
           f"  {g('ry')} {g('fz')} * {cell('ux')} th!  0 {g('rx')} - {g('fz')} * {cell('uy')} th!  {g('pbc')} {cell('uz')} th!",
           f"  INDEXOF_ROTATION_B th-cam@ {cell('pa')} th!  0 INDEXOF_ROTATION_C th-cam@ - {cell('pc')} th! ;",
           # ( u v depth actor -- ): u and v in panel metres
           ": th-pplace",
           f"  {cell('pac')} th! {cell('pdp')} th! {cell('pq')} th! {cell('pu')} th!",
           f"  {g('pdp')} {n(pn.DEPTH)} / {cell('psc')} th!",
           f"  {g('pu')} {g('pcu')} + {g('psc')} * {cell('pu')} th!  {g('pq')} {g('psc')} * {cell('pq')} th!",
           f"  {g('kx')} {g('pdp')} {g('fx')} * + {g('pu')} {g('rx')} * + {g('pq')} {g('ux')} * + {g('pac')} th-x",
           f"  {g('ky')} {g('pdp')} {g('fy')} * + {g('pu')} {g('ry')} * + {g('pq')} {g('uy')} * + {g('pac')} th-y",
           f"  {g('kz')} {g('pdp')} {g('fz')} * + {g('pq')} {g('uz')} * + {g('pac')} th-z",
           f"  {g('pa')} {g('pac')} th-a  {g('pc')} {g('pac')} th-c",
           f"  {g('psc')} {g('pac')} th-sx  {g('psc')} {g('pac')} th-sy  {g('psc')} {g('pac')} th-sz ;",
           # ( u v value actor -- ): a drum, its axis R_DRUM behind its front digit, turned about the camera's right axis
           ": th-pdrum",
           f"  {cell('pac')} th! {cell('pdv')} th! {cell('pq')} th! {g('pcu')} + {cell('pu')} th!",
           f"  {g('kx')} {n(pn.DEPTH + pn.R_DRUM)} {g('fx')} * + {g('pu')} {g('rx')} * + {g('pq')} {g('ux')} * + {g('pac')} th-x",
           f"  {g('ky')} {n(pn.DEPTH + pn.R_DRUM)} {g('fy')} * + {g('pu')} {g('ry')} * + {g('pq')} {g('uy')} * + {g('pac')} th-y",
           f"  {g('kz')} {n(pn.DEPTH + pn.R_DRUM)} {g('fz')} * + {g('pq')} {g('uz')} * + {g('pac')} th-z",
           f"  {g('pa')} {g('pdv')} {n(pn.SLOT_REV)} * + {g('pac')} th-a  {g('pc')} {g('pac')} th-c ;"]

    def put(name: str, layer: str, u: str, v: str) -> str:
        return f"  {u} {v} {n(pn.D[layer])} {A(name)} th-pplace"

    # the two readings rows: each drum's value from the scan's first high or low still ahead
    out.append(": th-pdrums")
    out.append(f"  {sc('rdy')} 0 > if")
    for row, (tn_, hn_) in enumerate((("nht", "nhh"), ("nlt", "nlh"))):
        out += [f"    {sc('rsec')} {sc(tn_)} + {cell('pt')} th!",
                f"    {g('pt')} 600 / .5 + th-floor 144 th-mod {cell('pslot')} th!  {g('pslot')} 6 / th-floor {cell('phour')} th!",
                f"    {sc(hn_)} 10 * .5 + th-floor 0 max {cell('pten')} th!"]
        values = {"h10": f"{g('phour')} 10 / th-floor", "h1": f"{g('phour')} 10 th-mod", "m10": f"{g('pslot')} 6 th-mod",
                  "t1": f"{g('pten')} 10 / th-floor", "t01": f"{g('pten')} 10 th-mod"}
        for name in pn.DRUMS:
            out.append(f"  {n(pn.row_u(name))} {n(pn.row_v(row))} {values[name]} {A(f'panel_drum_{row}_{name}')} th-pdrum")
    out += ["  then ;"]
    L = [": th-panel", "  th-pframe", f"  {g('t')} 1800 th-mod 900 / dup 1 > if 2 swap - then .5 * cos-rev {n(pn.PAN_KM / 2.0 * pn.M_PER_KM)} * {n(-pn.BAND_H / 2.0)} + {cell('pm')} th!",
         put("panel_paper", "paper", "0", "0"), put("panel_map", "map", "0", g("pm")), put("panel_col_body", "column", "0", "0"),
         put("panel_col_fill", "fill", n(pn.COL_X), n(pn.COL_V0)),
         f"  {g('tide')} {n(1.0 / pn.COL_MAX_M)} * th-c01 .01 max {g('psc')} * {A('panel_col_fill')} th-sz",
         put("panel_col_ptr", "pointer", n(pn.COL_X + pn.PTR_DU), f"{g('tide')} {n(1.0 / pn.COL_MAX_M)} * th-c01 {n(pn.COL_V1 - pn.COL_V0)} * {n(pn.COL_V0)} +"),
         put("panel_band_back", "plate", "0", "0"), "  th-pdrums", put("panel_band_mask", "mask", "0", "0"),
         put("panel_arrow_up", "arrow", n(pn.row_u("arrow")), n(pn.H / 2.0 - pn.ROW_H)),
         put("panel_arrow_dn", "arrow", n(pn.row_u("arrow")), n(pn.H / 2.0 - pn.ROW_H)), ";"]
    return out + L


def poll_words(ix: Dict[str, int], fields: Dict[str, int]) -> List[str]:
    """Copy each TideHarbourSettings field into its cell with property@ ( actor field -- value valid ); th-sv counts
    the fields that answered, so the engine check can prove the object was read. A field that does not answer
    leaves its cell as it was (0, the default, until the first read)."""
    out = [f": th-settings {ix[tl.SETTINGS_ACTOR]} ;"]
    out += [f": th-f-{k} {fields[label]} ;" for k, label in tl.FIELD_LABELS.items()]
    out += [": th-poll", f"  0 {cell('sv')} th!"]
    for k in tl.OPTION_CELLS:
        out.append(f"  th-settings th-f-{k} property@ if th-opt-{k} th! {get('sv')} 1 + {cell('sv')} th! else drop then")
    out.append(";")
    return out


def settings_fields() -> Dict[str, int]:
    """The field indices the level build read from the catalog tool and wrote to actor-map.json."""
    return json.loads((Path(__file__).resolve().parent / "actor-map.json").read_text())["settings_fields"]


def scan_words() -> List[str]:
    """The next high and low water, as turns.next_high_low (one scan, SCAN_BURST samples a frame).

    th-scan starts a scan on every ten-minute mark of the clock (and when there is no result yet), takes SCAN_BURST
    samples of the tide a frame at 10 minute steps from the mark, finds each change of direction, places it with a
    parabola through the three samples round it, and keeps it by the streaming rule of turns.filtered. A finished
    scan is copied to the result buffer, and every tick th-sc-pick reads from it the first high and first low
    still ahead: th-sc-nht/nhh (the next high: seconds after the scan's start, metres), th-sc-nlt/nlh (the next low),
    th-sc-rise (1 when the next turn is a high), th-sc-rsec/rday (the scan's start). So the reading is a function of
    the time alone, as turns.panel_reading.
    It reuses th-tide-sum and so overwrites the dd, hh, q64 and r64 cells (th-slow has finished with them) and
    restores th-tide, which the frame words use.
    """
    g = lambda name: f"th-sc-{name} th@"
    st = lambda name: f"th-sc-{name} th!"
    step, last = int(turns.STEP_S), turns.N_SAMPLES - 1
    out = []
    out += [
        ": th-sc-kept ( i k -- addr ) swap 3 * + " + str(KEPT0) + " + ;",        # k: 0 time, 1 height, 2 kind
        # the tide at the scan's start plus s samples ( s -- metres )
        ": th-sc-y",
        f"  {step} * {g('s0sec')} + 3600 /",
        "  dup 24 / th-floor",
        f"  dup {g('s0day')} + th-dd th!",
        "  24 * - th-hh th!",
        "  th-tide th@ >r th-tide-sum th-tide th@ r> th-tide th! ;",
        # append the candidate (tt seconds, tv metres, tk 1 for a high) to the kept turns, room permitting
        ": th-sc-append",
        f"  {g('nt')} {turns.KEPT_MAX} < if",
        f"    {g('tt')} {g('nt')} 0 th-sc-kept th!  {g('tv')} {g('nt')} 1 th-sc-kept th!  {g('tk')} {g('nt')} 2 th-sc-kept th!",
        f"    {g('nt')} 1 + {st('nt')}",
        "  then ;",
        ": th-sc-replace",
        f"  {g('tt')} {g('nt')} 1 - 0 th-sc-kept th!  {g('tv')} {g('nt')} 1 - 1 th-sc-kept th!  {g('tk')} {g('nt')} 1 - 2 th-sc-kept th! ;",
        # turns.filtered: the same kind as the last kept replaces it if more extreme; the other kind is kept if 4 cm away
        ": th-sc-add",
        f"  {g('nt')} 0 = if th-sc-append else",
        f"    {g('nt')} 1 - 2 th-sc-kept th@ {st('lk')}  {g('nt')} 1 - 1 th-sc-kept th@ {st('lh')}",
        f"    {g('lk')} {g('tk')} = if",
        f"      {g('tv')} {g('lh')} > if 1 else 0 then {g('tk')} = if th-sc-replace then",
        "    else",
        f"      {g('tv')} {g('lh')} - dup * {n(turns.MIN_SWING_M ** 2)} < if 0 else 1 then {st('ok')}",
        f"      {g('ok')} if th-sc-append then",
        "    then",
        "  then ;",
        # the middle sample yb of ya, yb, yc is a turn if the direction changes there
        ": th-sc-turn",
        f"  {g('yb')} {g('ya')} - {g('yc')} {g('yb')} - * 0 < if",
        f"    {g('ya')} {g('yb')} 2 * - {g('yc')} + {st('den')}",
        f"    {g('ya')} {g('yc')} - .5 * {g('den')} / {st('off')}",
        f"    {g('yb')} {g('ya')} {g('yc')} - .25 * {g('off')} * - {st('tv')}",
        f"    {g('yb')} {g('ya')} > if 1 else 0 then {st('tk')}",
        f"    {g('s')} 1 - {g('off')} + {step} * {st('tt')}",
        "    th-sc-add",
        "  then ;",
        ": th-sc-start",
        f"  th-day th@ {tl.EPOCH_DAY} - {st('s0day')}  th-key th@ {int(turns.MARK_S)} / th-floor {int(turns.MARK_S)} * {st('s0sec')}",
        f"  {g('s0day')} 144 * {g('s0sec')} {int(turns.MARK_S)} / + {st('cmark')}",
        f"  -1 {st('s')}  0 {st('nt')}  1 {st('act')} ;",
        # the result buffer: element i, field k ( i k -- addr )
        ": th-sc-res ( i k -- addr ) swap 3 * + " + str(RES0) + " + ;",
        # after the last sample: the scan becomes the result
        ": th-sc-finish",
        f"  {g('nt')} {st('rn')}",
        f"  0 {st('i')}",
        f"  {g('nt')} 0 > if",
        "    begin",
        f"      {g('i')} 0 th-sc-kept th@ {g('i')} 0 th-sc-res th!  {g('i')} 1 th-sc-kept th@ {g('i')} 1 th-sc-res th!  {g('i')} 2 th-sc-kept th@ {g('i')} 2 th-sc-res th!",
        f"      {g('i')} 1 + dup {st('i')} {g('nt')} =",
        "    until",
        "  then",
        f"  {g('s0day')} {st('rday')}  {g('s0sec')} {st('rsec')}  1 {st('rdy')}  0 {st('act')} ;",
        # every tick: the first high and the first low water still ahead of now, and whether the next turn is a high
        ": th-sc-pick",
        f"  -1 {st('nht')}  -1 {st('nlt')}  -1 {st('first')}",
        f"  th-day th@ {tl.EPOCH_DAY} - {g('rday')} - 86400 * th-key th@ + {g('rsec')} - {st('now')}",
        f"  {g('rdy')} 0 > {g('rn')} 0 > & if",
        f"    0 {st('i')}",
        "    begin",
        f"      {g('i')} 0 th-sc-res th@ {g('now')} > if",
        f"        {g('first')} 0 < if {g('i')} 2 th-sc-res th@ {st('rise')}  1 {st('first')} then",
        f"        {g('i')} 2 th-sc-res th@ 1 = if",
        f"          {g('nht')} 0 < if {g('i')} 0 th-sc-res th@ {st('nht')}  {g('i')} 1 th-sc-res th@ {st('nhh')} then",
        "        else",
        f"          {g('nlt')} 0 < if {g('i')} 0 th-sc-res th@ {st('nlt')}  {g('i')} 1 th-sc-res th@ {st('nlh')} then",
        "        then",
        "      then",
        f"      {g('i')} 1 + dup {st('i')} {g('rn')} =",
        "    until",
        "  then ;",
        # one sample: the first two prime ya and yb; from the third on, yb is tested
        ": th-sc-step",
        f"  {g('s')} th-sc-y {st('yc')}",
        f"  {g('s')} 1 < if else th-sc-turn then",
        f"  {g('yb')} {st('ya')}  {g('yc')} {st('yb')}",
        f"  {g('s')} 1 + {st('s')}",
        f"  {g('s')} {last} > if th-sc-finish then ;",
        ": th-scan",
        f"  {g('act')} 0 = if",
        f"    {g('rdy')} 0 = if th-sc-start else",
        f"      th-day th@ 144 * {tl.EPOCH_DAY * 144} - th-key th@ {int(turns.MARK_S)} / th-floor + {g('cmark')} <> if th-sc-start then",
        "    then",
        "  then",
        f"  {g('act')} if",
        f"    0 {st('bi')}",
        "    begin",
        f"      th-sc-step {g('bi')} 1 + dup {st('bi')} {SCAN_BURST} = {g('act')} 0 = | ",
        "    until",
        "  then",
        "  th-sc-pick ;",
    ]
    return out


def tick() -> List[str]:
    return [": th-tick",
            f"  INDEXOF_WALL_HOUR th@ {cell('hr')} th!  INDEXOF_WALL_MINUTE th@ {cell('mi')} th!",
            f"  INDEXOF_WALL_SECOND th@ {cell('sec')} th!  INDEXOF_WALL_DAY th@ {cell('day')} th!",
            f"  {get('mi')} 60 * {get('sec')} + {cell('t')} th!",
            f"  {get('hr')} 3600 * {get('mi')} 60 * + {get('sec')} th-floor + {cell('key')} th!",
            f"  {get('key')} {get('ckey')} <> {get('day')} 1 + {get('cday')} <> | if th-slow then",
            "  th-poll th-scan",
            "  th-bars th-boats th-sky th-lights th-clock th-panel th-show",
            f"  {get('q')} 100 + th-prevq th@ <> if th-recolour {get('q')} 100 + th-prevq th! then ;"]


def default_indices() -> Dict[str, int]:
    """Made-up actor indices for tests: each group contiguous, as the level builder guarantees."""
    names = (list(parts.all_meshes()) + [m.name for m in parts.static_meshes() + parts.toggled_static_meshes()]
             + ["Camera", "cs_wide", "LookAt", tl.SETTINGS_ACTOR])
    return {name: 100 + i for i, name in enumerate(names)}


def definitions(ix: Dict[str, int], fields: Dict[str, int] | None = None) -> str:
    """The script without its per-frame call (the last line, th-tick)."""
    fields = fields or settings_fields()
    lines = (library() + tide_sum() + sun_words() + slow_words() + palette_words() + recolour_words(ix)
             + panel_words(ix) + frame_words(ix) + poll_words(ix, fields) + scan_words() + tick())
    return "\n".join(lines) + "\n"


def director_script(ix: Dict[str, int], fields: Dict[str, int] | None = None) -> str:
    return definitions(ix, fields) + "\nth-tick\n"


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--indices", metavar="actor-map.json", help="actor-map.json from the level build (indices: name -> index)")
    ap.add_argument("--out", metavar="FILE.fth", help="write the script here (default: stdout)")
    args = ap.parse_args(argv)
    ix = json.load(open(args.indices))["indices"] if args.indices else default_indices()
    text = director_script(ix)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
