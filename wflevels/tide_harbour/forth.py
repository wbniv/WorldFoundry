#!/usr/bin/env python3
"""Generate the Tide Harbour director script (zForth).

The director poses, colours and shows every moving thing each frame from WALL_DAY, WALL_HOUR,
WALL_MINUTE and WALL_SECOND, and from the settings cells, following timeline.py one formula for one:

    director_script(indices) -> str     indices: actor name -> runtime index (actor-map.json)

Once per whole second (when the second or the day changes) it sums the tide, places the sun and
works out the look of the light; every frame it poses the waves, boats, hands, birds and camera.
When the look's whole-degree step changes it re-colours every re-coloured material through the
FACE_COLOR mailboxes (3037 + slot). tests/verify_tide_harbour_forth.py runs this script in the real
zForth VM against timeline.scene; scripts/check-tide-harbour.py runs it in the engine.

Global user mailboxes: 600-659 scratch, 689 the last look step, 690-693 the settings (copied every frame
from the TideHarbourSettings object with property@, plan D13; 0 is the default), 700-706 visibility,
720-783 the next-turn scan (scan_words).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List

import parts
import timeline as tl
import turns

CELLS = ["t", "sod", "hr", "mi", "sec", "day", "key", "ckey", "cday", "tide", "q", "w1", "w2", "w3", "w4", "w5",
         "kr", "kg", "kb", "hor-r", "hor-g", "hor-b", "zen-r", "zen-g", "zen-b", "sun-r", "sun-g", "sun-b", "lit",
         "dd", "hh", "q64", "r64", "g", "eqt", "dec", "sd", "cd", "ha", "sh", "ch", "up", "no", "we", "alt", "mf",
         "son", "mon", "i", "u", "bz", "dy", "dz", "az", "sn", "cs", "kk", "sv"]
assert 600 + len(CELLS) <= 689
PREVQ = 689
SCAN0 = 720                      # the next-turn scan's cells: 720-759 state and results, 760-783 the kept turns (8 x t, h, kind)
SCAN_BURST = 20                  # samples per frame: a scan of 182 takes about ten frames, and runs only when a turn has passed
SCAN_CELLS = ["s", "s0day", "s0sec", "ya", "yb", "yc", "nt", "act", "rdy", "nht", "nhh", "nlt", "nlh", "rday", "rsec", "rise",
              "tt", "tv", "tk", "i", "first", "ahead", "lk", "lh", "ok", "den", "off", "bi"]
KEPT0 = 760
assert len(SCAN_CELLS) <= KEPT0 - SCAN0
WORDS = {"floor", "frac", "trunc", "mod", "c01", "x", "y", "z", "a", "b", "c", "sx", "sy", "sz", "col", "byte", "pack",
         "ramp", "tide-sum", "sun", "slow", "palette", "bar-rgb", "recolour", "bars", "boats", "sky", "lights", "clock",
         "show", "tick", "prevq", "poll", "settings", "scan"} | {"opt-" + k for k in tl.OPTION_CELLS} | {"f-" + k for k in tl.OPTION_CELLS}
WORDS |= {"sc-" + c for c in SCAN_CELLS} | {"sc-y", "sc-add", "sc-turn", "sc-step", "sc-start", "sc-finish", "sc-kept", "sc-append", "sc-replace"}


def check_names() -> None:
    """A cell and a word must never share a name: the later definition would shadow the earlier."""
    clash = WORDS & set(CELLS)
    assert not clash, f"cells shadow words: {sorted(clash)}"


def n(x: float) -> str:
    """A literal zForth parses: fixed point, no exponent, enough digits for a float32."""
    s = f"{x:.10f}".rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def cell(name: str) -> str:
    return f"th-{name}"


def get(name: str) -> str:
    return f"th-{name} th@"


def library() -> List[str]:
    check_names()
    out = ["\\ Tide Harbour director (generated by wflevels/tide_harbour/forth.py; do not edit)",
           ": th@ read-mailbox ; : th! write-mailbox ;"]
    out += [f": th-{c} {600 + i} ;" for i, c in enumerate(CELLS)]
    out += [f": th-prevq {PREVQ} ;"]
    out += [f": th-opt-{k} {v} ;" for k, v in tl.OPTION_CELLS.items()]
    out += [
        ": th-c01 0 max 1 min ;",
        ": th-trunc 16777216 % ;",                                         # toward zero, as C's int cast
        ": th-floor dup th-trunc swap over - 0 < if 1 - then ;",
        ": th-frac dup th-floor - ;",
        ": th-mod ( a b -- r ) over over / th-floor * - ;",
        ": th-x ( v actor -- ) INDEXOF_X_POS swap write-actor-mailbox ;",
        ": th-y ( v actor -- ) INDEXOF_Y_POS swap write-actor-mailbox ;",
        ": th-z ( v actor -- ) INDEXOF_Z_POS swap write-actor-mailbox ;",
        ": th-a ( v actor -- ) INDEXOF_ROTATION_A swap write-actor-mailbox ;",
        ": th-b ( v actor -- ) INDEXOF_ROTATION_B swap write-actor-mailbox ;",
        ": th-c ( v actor -- ) INDEXOF_ROTATION_C swap write-actor-mailbox ;",
        ": th-sx ( v actor -- ) INDEXOF_X_SCALE swap write-actor-mailbox ;",
        ": th-sy ( v actor -- ) INDEXOF_Y_SCALE swap write-actor-mailbox ;",
        ": th-sz ( v actor -- ) INDEXOF_Z_SCALE swap write-actor-mailbox ;",
        ": th-col ( packed actor slot -- ) INDEXOF_FACE_COLOR_TOP + swap write-actor-mailbox ;",
        ": th-byte th-c01 255 * .5 + th-trunc ;",
        ": th-pack ( r g b -- n ) th-byte swap th-byte 256 * + swap th-byte 65536 * + ;",
        ": th-ramp ( q k dk -- w ) >r - r> / th-c01 ;",
    ]
    return out


