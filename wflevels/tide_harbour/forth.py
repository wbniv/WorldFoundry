def palette_words() -> List[str]:
    """The ramp weights and the palette cells (timeline.palette), from the look step th-q."""
    out = [": th-palette"]
    keys = tl.KEYS
    for i in range(len(keys) - 1):
        out.append(f"  {get('q')} {n(keys[i])} {n(keys[i + 1] - keys[i])} th-ramp {cell('w' + str(i + 1))} th!")

    def channel(values, target):
        body = n(values[0])
        for i in range(len(values) - 1):
            body += f" {n(values[i + 1] - values[i])} {get('w' + str(i + 1))} * +"
        out.append(f"  {body} {cell(target)} th!")
    names = {"k": ("kr", "kg", "kb"), "hor": ("hor-r", "hor-g", "hor-b"), "zen": ("zen-r", "zen-g", "zen-b"),
             "sun": ("sun-r", "sun-g", "sun-b")}
    for pal, cells in names.items():
        for ch in range(3):
            channel([key[ch] for key in tl.PALETTES[pal]], cells[ch])
    channel(tl.LIT_KEYS, "lit")
    out.append(";")
    return out


K = ("kr", "kg", "kb")
HOR = ("hor-r", "hor-g", "hor-b")
ZEN = ("zen-r", "zen-g", "zen-b")
SUN = ("sun-r", "sun-g", "sun-b")


def colour_expr(kind: str, day, lit, arg: float) -> str:
    """Forth that leaves r g b, as timeline.colour_of(kind, ...)."""
    out = []
    for ch in range(3):
        if kind == "k":
            out.append(f"{n(day[ch])} {get(K[ch])} *")
        elif kind == "lit":
            out.append(f"{n(day[ch])} {get(K[ch])} * dup {n(lit[ch])} swap - {get('lit')} * +")
        elif kind == "soft":
            out.append(f"{n(day[ch])} {get(K[ch])} .5 * .5 + *")
        elif kind == "sky":
            out.append(f"{get(HOR[ch])} dup {get(ZEN[ch])} swap - {n(arg)} * +")
        elif kind == "cloud":
            out.append(f"{n(day[ch])} {get(K[ch])} * dup {get(HOR[ch])} swap - .35 * +")
        elif kind == "glint":
            out.append(f"{get(HOR[ch])} .8 * .25 + dup {n(tl.MOON_GLINT[ch])} swap - {get('lit')} * +")
        elif kind == "sun":
            out.append(get(SUN[ch]))
        else:
            raise ValueError(kind)
    return " ".join(out)


def bar_rgb() -> List[str]:
    """( u -- r g b ): a water bar's colour, far (u = 0) to near (u = 1), as timeline.colour_of('bar')."""
    lines = [": th-bar-rgb", f"  {cell('u')} th!"]
    for ch in range(3):
        far = f"{get(HOR[ch])} .55 * {get(K[ch])} {n(tl.WATER_FAR_DAY[ch])} * .45 * +"
        near = f"{get(K[ch])} {n(tl.WATER_NEAR_DAY[ch])} * {get(ZEN[ch])} .25 * +"
        lines.append(f"  {far} dup {near} swap - {get('u')} * +")
    lines.append(";")
    return lines


def recolour_words(ix: Dict[str, int]) -> List[str]:
    slots = parts.recolour_slots()
    lines = bar_rgb() + [": th-recolour", "  th-palette"]
    bar0 = ix["bar_00"]
    lines += ["  0 th-i th!", "  begin",
              f"    1 {get('i')} {tl.N_BARS - 1} / - th-bar-rgb th-pack {bar0} {get('i')} + 0 th-col",      # nearness: bar 0 is the nearest
              f"    {get('i')} 1 + dup th-i th! {tl.N_BARS} =", "  until"]
    for name, entries in slots.items():
        if name.startswith("bar_"):
            continue
        for slot, kind, day, lit, arg in entries:
            lines.append(f"  {colour_expr(kind, day, lit, arg)} th-pack {ix[name]} {slot} th-col")
    lines.append(";")
    return lines


