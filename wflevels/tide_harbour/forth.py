def tide_sum() -> List[str]:
    """The 64 waves, in the split form of timeline.tide_split_m, into th-tide."""
    out = [": th-tide-sum",
           f"  {get('dd')} {tl.TIDE_SPLIT} / th-floor {cell('q64')} th!",
           f"  {get('dd')} {tl.TIDE_SPLIT} {get('q64')} * - {cell('r64')} th!",
           f"  {n(tl.Z0)}"]
    for amp, a64, a, cph, ph in tl.TERMS:
        out.append(f"  {n(a64)} {get('q64')} * {n(a)} {get('r64')} * + {n(cph)} {get('hh')} * + {n(ph)} + cos-rev {n(amp)} * +")
    out.append(f"  {cell('tide')} th! ;")
    return out


def sun_words() -> List[str]:
    import math
    phi = math.radians(tl.LAT_DEG)
    sp, cp = math.sin(phi), math.cos(phi)
    g = get("g")
    return [
        ": th-sun",
        f"  {get('dd')} {get('hh')} 12 - 24 / + {n(tl.YEAR_DAYS)} / {cell('g')} th!",
        # the equation of time (minutes) and the declination (radians): NOAA's series in the year angle
        f"  {g} sincos-rev {cell('cs')} th! {cell('sn')} th!",
        f"  {n(0.000075)} {n(0.001868)} {get('cs')} * + {n(-0.032077)} {get('sn')} * +",
        f"  {n(0.006918)} {n(-0.399912)} {get('cs')} * + {n(0.070257)} {get('sn')} * +",
        f"  {g} 2 * sincos-rev {cell('cs')} th! {cell('sn')} th!",
        f"  swap {n(-0.014615)} {get('cs')} * + {n(-0.040849)} {get('sn')} * + {n(229.18)} * {cell('eqt')} th!",
        f"  {n(-0.006758)} {get('cs')} * + {n(0.000907)} {get('sn')} * +",
        f"  {g} 3 * sincos-rev {cell('cs')} th! {cell('sn')} th!",
        f"  {n(-0.002697)} {get('cs')} * + {n(0.00148)} {get('sn')} * + {cell('dec')} th!",
        f"  {get('dec')} {n(1 / (2 * math.pi))} * sincos-rev {cell('cd')} th! {cell('sd')} th!",
        # the hour angle from true solar time, then the unit vector toward the sun
        f"  {get('key')} 60 / {get('eqt')} + {n(4.0 * tl.LON_DEG - 60.0 * tl.ZONE_H)} + 1440 / .5 - {cell('ha')} th!",
        f"  {get('ha')} sincos-rev {cell('ch')} th! {cell('sh')} th!",
        f"  {n(sp)} {get('sd')} * {n(cp)} {get('cd')} * {get('ch')} * + {cell('up')} th!",
        f"  {n(cp)} {get('sd')} * {n(sp)} {get('cd')} * {get('ch')} * - {cell('no')} th!",
        f"  {get('cd')} {get('sh')} * {cell('we')} th!",
        f"  90 {get('up')} acos-rev 360 * - {cell('alt')} th!",
        f"  {get('alt')} th-floor {tl.LOOK_BOTTOM} max {tl.LOOK_TOP} min {cell('q')} th!",
        f"  {get('ha')} .25 - th-frac 2 * {cell('mf')} th!",
        f"  {get('we')} .5 > {get('alt')} -2 > & {get('alt')} 25 < & if 1 else 0 then {cell('son')} th!",
        f"  {get('mf')} 0 > {get('mf')} 1 < & {get('alt')} -4 < & if 1 else 0 then {cell('mon')} th! ;",
    ]


